-- SIPKAK database schema for Supabase (Postgres).
-- Run this once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- It only creates what is missing, so running it again is safe and keeps your data.
--
-- Row Level Security is ON for every table and there are NO policies, so the public
-- (anon) key can't read or write anything. Only the backend, using the secret key, can.

create table if not exists reports (
  id            bigint generated by default as identity primary key,
  description   text not null check (char_length(description) between 5 and 280),
  category      text not null default 'other'
                  check (category in ('lighting', 'paths', 'toilets', 'classroom', 'accessibility', 'other')),
  building      text not null,
  floor         text check (floor is null or char_length(floor) <= 20),
  lat           double precision not null,
  lng           double precision not null,
  accuracy_m    double precision not null default 12,
  photo         text,  -- SIMULATED: a JPEG data URL; the real app would store a Storage URL
  status        text not null default 'waiting'
                  check (status in ('waiting', 'in_progress', 'done')),
  note          text,
  confirmations integer not null default 0,
  reporter_id   text not null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- For databases created before categories existed: adds the column (old rows become 'other').
alter table reports add column if not exists category text not null default 'other'
  check (category in ('lighting', 'paths', 'toilets', 'classroom', 'accessibility', 'other'));

create index if not exists reports_created_at_idx on reports (created_at desc);
create index if not exists reports_reporter_id_idx on reports (reporter_id);

-- Every status a report has had, oldest first. The first row is "waiting" at created_at.
create table if not exists report_history (
  id        bigint generated always as identity primary key,
  report_id bigint not null references reports (id) on delete cascade,
  status    text not null check (status in ('waiting', 'in_progress', 'done')),
  at        timestamptz not null
);

create index if not exists report_history_report_id_idx on report_history (report_id, at);

-- Who gave which report a "+1". The primary key stops anyone confirming twice.
create table if not exists confirmations (
  report_id   bigint not null references reports (id) on delete cascade,
  reporter_id text not null,
  created_at  timestamptz not null default now(),
  primary key (report_id, reporter_id)
);

create table if not exists notifications (
  id          bigint generated by default as identity primary key,
  reporter_id text not null,
  report_id   bigint not null references reports (id) on delete cascade,
  kind        text not null check (kind in ('status', 'note')),
  status      text check (status in ('waiting', 'in_progress', 'done')),
  note        text,
  read        boolean not null default false,
  created_at  timestamptz not null default now()
);

create index if not exists notifications_reporter_id_idx
  on notifications (reporter_id, created_at desc);

alter table reports enable row level security;
alter table report_history enable row level security;
alter table confirmations enable row level security;
alter table notifications enable row level security;

-- Records a "+1" and bumps the count in one step, so two clicks at once can't both count.
-- Returns the new count, or null if this reporter had already confirmed the report.
create or replace function add_confirmation(p_report_id bigint, p_reporter_id text)
returns integer
language plpgsql
as $$
declare
  new_count integer;
begin
  insert into confirmations (report_id, reporter_id)
  values (p_report_id, p_reporter_id)
  on conflict do nothing;

  if not found then
    return null;
  end if;

  update reports
  set confirmations = confirmations + 1
  where id = p_report_id
  returning confirmations into new_count;

  return new_count;
end;
$$;

-- Only the backend (secret key) may call it.
revoke execute on function add_confirmation(bigint, text) from public, anon, authenticated;
